"""Deterministic Graf catalogue, reference tables and per-factory integration checks.

The reviewed data is units-catalogue.json. Independent physical anchors and
prefix behavior are maintained separately in tests/units/catalogue-anchors.graf
and tests/units/prefixes.graf; generated checks do not replace those assertions.
"""
from __future__ import annotations
import argparse
import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def graf_number(value: str | Fraction) -> str:
    """An exact Graf integer or rational literal, never a decimal float."""
    value = Fraction(value)
    if value.denominator == 1:
        return str(value.numerator)
    remaining = value.denominator
    for prime in (2, 5):
        while remaining % prime == 0:
            remaining //= prime
    if remaining == 1:
        digits = 0
        multiplier = 1
        while multiplier % value.denominator:
            multiplier *= 10
            digits += 1
        magnitude = abs(value.numerator) * multiplier // value.denominator
        text = str(magnitude).zfill(digits + 1)
        sign = "-" if value < 0 else ""
        return sign + text[:-digits] + "." + text[-digits:] + "(0)"
    return f"{value.numerator}.exact-quotient({value.denominator})"


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def bool_name(value: bool) -> str:
    return "yes" if value else "no"


def generated_files(data: dict) -> dict[Path, str]:
    """Source files and references produced from the reviewed catalogue records."""
    result = {}
    core_import = 'import(open-graf-units-core: graf {path: "core"});\n\n'
    units_import = 'import(units: graf {path: "."});\n\n'
    rows = data['units']
    names = [row['name'] for row in rows]
    assert len(names) == len(set(names)), 'duplicate public factory'
    existing = set(p.stem for p in (ROOT/'src/units').glob('*.graf'))
    dimensions = dict(data['families'])
    for name in existing:
        path = ROOT/'src/units'/f'{name}.graf'
        text = path.read_text()
        if '.unit.family(' in text:
            vector = text.split('.dimension(', 1)[1].split(')', 1)[0]
            dimensions[name] = [int(n) for n in vector.split(',')]
    dimensions['angle'] = [0]*8
    # This special family now lives in the canonical core rather than its public wrapper.
    dimensions['temperature-point'] = [0, 0, 0, 0, 1, 0, 0, 0]
    for name, vector in data['families'].items():
        assert len(vector) == 8 and all(isinstance(n, int) for n in vector)
        result[ROOT/'src/units'/f'{name}.graf'] = '// Generated by tools/units_catalogue.py; review tools/units-catalogue.json.\n' + core_import + f'open-graf-units-core.unit.family({quoted(name)},\n\topen-graf-units-core.dimension({", ".join(map(str,vector))}))\n'
    for system, key, radix in [('si','decimal_prefixes',10),('binary','binary_prefixes',2)]:
        source = 'BIPM-SI-9-v4.01/Table 7' if radix == 10 else 'BIPM-SI-9-v4.01/Chapter 3; IEC-80000-13-2025'
        lines = [core_import+'namespace {']
        for name, symbol, exponent in data[key]:
            lines.append(f'\t{name}: open-graf-units-core.prefix({quoted(name)}, {quoted(symbol)}, {radix}, {exponent}, {quoted(source)}),')
        result[ROOT/'src/units'/f'{system}-prefixes.graf'] = '\n'.join(lines).rstrip(',')+'\n}\n'
    for row in rows:
        assert row['family'] in dimensions, row
        if row.get('existing'):
            continue
        if 'prefix' in row:
            base = next(r for r in rows if r['name']==row['base'])
            assert base['prefixable'] if row['system']=='decimal' else base.get('binary_prefixable',False)
            assert 'prefix' not in base, 'double prefix'
            key = 'si-prefixes' if row['system']=='decimal' else 'binary-prefixes'
            body = f'units.{key}.{row["prefix"]}(units.{row["base"]})'
        elif 'power' in row:
            body = f'units.{"square" if row["power"]==2 else "cube"}(units.{row["base"]})'
        else:
            factor = row['expression'] if 'expression' in row else graf_number(row['scale'])
            body = f'units.{row["family"]}.definition({quoted(row["id"])}, {quoted(row["symbol"])}, {factor},\n\t{bool_name(row["prefixable"])}, {bool_name(row["exact"])}, {quoted(row["source"])})'
            if row.get('binary_prefixable') or row.get('uncertainty'):
                props = []
                if row.get('binary_prefixable'):
                    props.append('\toverride>> binary-prefixable: yes')
                if row.get('uncertainty'):
                    assert not row['exact']
                    props += ['\toverride>> scale-uncertainty: '+graf_number(row['uncertainty']), '\toverride>> reference-edition: '+quoted(row['reference_edition'])]
                body = 'definition$ = '+body+';\n\nheir(definition$) {\n'+',\n'.join(props)+'\n}'
        header = '// Generated by tools/units_catalogue.py; review tools/units-catalogue.json.\n'
        result[ROOT/'src/units/core/catalogue-definitions'/f'{row["name"]}.graf'] = header + units_import.replace('path: "."', 'path: "../.."') + body + '\n'
        result[ROOT/'src/units'/f'{row["name"]}.graf'] = header + core_import + 'open-graf-units-core.catalogue-definitions.' + row['name'] + '\n'
    # A finite, explicit catalogue relation; special definitions have separate rule tests.
    special_rows = data.get('special_units', [])
    assert not set(names).intersection(row['name'] for row in special_rows)
    all_rows = rows + special_rows
    result[ROOT/'src/units/catalogue.graf'] = units_import+'box {\n'+',\n'.join('\tdefinition: units.'+row['name'] for row in all_rows)+'\n}\n'
    lines = ['// Generated construction checks; special rules have independent hand-written tests.',
             'import(units: graf {path: "../../../src/units"});', 'box {']
    for row in special_rows:
        name = row['name']
        lines += [f'\tcommon.testing.gunit.test>> verify-{name}(): (',
                  f'\t\tq$ = units.{name}(2);',
                  f'\t\tcommon.testing.gunit.assert-equals(tuple {{2, units.{name}, yes}},',
                  '\t\t\ttuple {q$.value(), q$.factory, match(q$, all(units.quantity?)?)});',
                  '\t\tcommon.testing.gunit.assert-fails {q$.amount := 3}', '\t),']
    result[ROOT/'tests/units/catalogue/special-factories.graf'] = '\n'.join(lines).rstrip(',')+'\n}\n'
    # Integration assertions independently exercise exports, types, dimensions and conversions.
    for batch in range(0,len(rows),25):
        lines = ['// Generated integration checks; see catalogue-anchors.graf for independent anchors.', 'import(units: graf {path: "../../../src/units"});', '', 'box {']
        for row in rows[batch:batch+25]:
            dim = ', '.join(map(str,dimensions[row['family']]))
            fields = ', '.join('q$.dimension.'+name for name in ['length','mass','duration','current','temperature','amount-of-substance','luminous-intensity','information'])
            body = [f'\tcommon.testing.gunit.test>> verify-{row["name"]}(): (',f'\t\tq$ = units.{row["name"]}(2);',f'\t\tcommon.testing.gunit.assert-equals(tuple {{2, yes, {dim}}},',f'\t\t\ttuple {{q$.value(), match(q$, units.{row["family"]}?), {fields}}});',f'\t\tcommon.testing.gunit.assert-equals(tuple {{units.{row["name"]}}}, tuple {{q$.factory}});']
            if not row.get('expression'):
                expected=graf_number(Fraction(row['scale'])*2)
                body.append(f'\t\tcommon.testing.gunit.assert-equals(tuple {{{expected}}}, tuple {{q$.coherent-value()}});')
            body += [f'\t\tcommon.testing.gunit.assert-equals(tuple {{2}}, tuple {{units.{row["name"]}(q$).value()}})', '\t),']
            lines.extend(body)
        result[ROOT/'tests/units/catalogue'/f'factories-{batch//25+1:02}.graf'] = '\n'.join(lines).rstrip(',')+'\n}\n'
    # Documentation is a technical reference, not a rendering of the secondary handbook.
    lines=['# Unit catalogue', '', 'This table contains **'+str(len(rows))+' linear/angular factories**. Each factory is', 'available as `units.<name>` and in `src/units/<name>.graf`. Import `src/units`', 'as shown in [the core API](core.md). [Prefixes](prefixes.md) also construct', 'local factories without registration. Symbols are metadata, not alternate labels.', '', 'Factors are relative to the coherent unit of the named family. All rational', 'factors are exact unless the row is marked **measured**. Symbolic pi remains', 'symbolic. See [sources and reviewed conventions](sources.md) for reference IDs.', 'The separate [special-unit reference](special.md) documents temperature points,', 'logarithmic scales and contextual conversions. This linear catalogue includes', 'temperature **differences**. The `catalogue.definition` relation enumerates all', str(len(all_rows))+' named factories, including the '+str(len(special_rows))+' special definitions.', '', '| Factory | Family | Symbol | Coherent factor | Source |', '| --- | --- | --- | --- | --- |']
    for row in rows:
        factor=row.get('expression',row['scale']).replace('exact-quotient','over').replace('exact-product','times')
        if not row['exact']: factor+=' **measured**, u='+row['uncertainty']+'; '+row['reference_edition']
        lines.append(f'| `{row["name"]}` | `{row["family"]}` | {row["symbol"]} | {factor} | {row["source"]} |')
    lines += ['', '## Family dimensions', '', 'The eight exponents are ordered as length, mass, duration, current, temperature,', 'amount of substance, luminous intensity and information. Kinds with equal', 'dimensions are intentionally separate; classification is explicit.', '', '| Family | Exponents |', '| --- | --- |']
    for name,vector in sorted(dimensions.items()):lines.append(f'| `{name}` | {", ".join(map(str,vector))} |')
    result[ROOT/'docs/units/catalogue.md']='\n'.join(lines)+'\n'
    return result


def write_catalogue(check: bool = False) -> None:
    data=json.loads((ROOT/'tools/units-catalogue.json').read_text())
    files=generated_files(data)
    mismatches=[]
    for path in (ROOT/'src/units').rglob('*.graf'):
        if path.read_text().startswith('// Generated by tools/units_catalogue.py') and path not in files:
            mismatches.append('Stale generated file: '+str(path.relative_to(ROOT)))
    for path,text in files.items():
        if check:
            if not path.exists() or path.read_text()!=text:mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text)
    if mismatches:raise SystemExit('Generated files differ: '+', '.join(mismatches))
    print(f'{len(files)} generated files '+('verified' if check else 'written'))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    write_catalogue(parser.parse_args().check)
